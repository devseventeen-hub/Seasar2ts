import * as path from "path";
import {
  DiconDefinition,
  DiconComponentDefinition,
  DiconArg,
  DiconProperty
} from "@seasar2ts/core";

export interface DiconGeneratorOptions {
  functionName?: string;
  importCorePath?: string;
  classImports?: Record<string, string>;
  declareMissingClasses?: boolean;
}

function capitalize(str: string): string {
  if (!str) return "";
  return str.charAt(0).toUpperCase() + str.slice(1);
}

function formatLiteralOrRef(arg: { value?: string; componentName?: string; expression?: string }): string {
  if (arg.componentName) {
    return `context.container.get("${arg.componentName}")`;
  }
  if (arg.expression) {
    return arg.expression;
  }
  if (arg.value !== undefined) {
    const val = arg.value;
    if (/^-?\d+(\.\d+)?$/.test(val)) {
      return val;
    }
    if (val === "true" || val === "false") {
      return val;
    }
    return JSON.stringify(val);
  }
  return "undefined";
}

export class DiconTsGenerator {
  generate(dicon: DiconDefinition, options: DiconGeneratorOptions = {}): string {
    const importCore = options.importCorePath || "@seasar2ts/core";
    const baseName = dicon.namespace || path.basename(dicon.filePath || "app", path.extname(dicon.filePath || "app"));
    const functionName = options.functionName || `configure${capitalize(baseName)}Container`;

    const lines: string[] = [];

    // Core imports
    const coreImports = new Set<string>(["S2HierarchicalContainer"]);

    const hasAspects = dicon.components.some(c => c.aspectDefs && c.aspectDefs.length > 0);
    if (hasAspects) {
      coreImports.add("applyPointcutAdvisors");
      coreImports.add("PointcutAdvisor");
    }

    lines.push(`import { ${Array.from(coreImports).join(", ")} } from "${importCore}";`);

    // Include imports
    for (const inc of dicon.includes) {
      const incBase = path.basename(inc.path, path.extname(inc.path));
      const incFn = `configure${capitalize(incBase)}Container`;
      const incImportPath = inc.path.endsWith(".dicon") ? `./${inc.path}` : `./${incBase}`;
      lines.push(`import { ${incFn} } from "${incImportPath}";`);
    }

    // Class imports
    const classNamesToImport = new Map<string, string>(); // simpleName -> importPath
    const missingClasses = new Set<string>();

    for (const comp of dicon.components) {
      if (comp.className) {
        const parts = comp.className.split(".");
        const simpleName = parts[parts.length - 1];

        const configuredImport = options.classImports?.[comp.className] || options.classImports?.[simpleName];
        if (configuredImport) {
          classNamesToImport.set(simpleName, configuredImport);
        } else if (options.declareMissingClasses) {
          missingClasses.add(simpleName);
        } else {
          // Default: derive relative import
          classNamesToImport.set(simpleName, `./${simpleName}`);
        }
      }
    }

    for (const [cls, imp] of classNamesToImport.entries()) {
      lines.push(`import { ${cls} } from "${imp}";`);
    }

    if (missingClasses.size > 0) {
      for (const cls of missingClasses) {
        lines.push(`declare const ${cls}: any;`);
      }
    }

    lines.push(``);
    lines.push(`// Generated by Seasar2ts DiconTsGenerator from: ${dicon.filePath}`);
    lines.push(`export function ${functionName}(container: S2HierarchicalContainer): void {`);

    // 1. Includes
    if (dicon.includes.length > 0) {
      lines.push(`  // 1. Include dependencies`);
      for (const inc of dicon.includes) {
        const incBase = path.basename(inc.path, path.extname(inc.path));
        const incFn = `configure${capitalize(incBase)}Container`;
        lines.push(`  ${incFn}(container);`);
      }
      lines.push(``);
    }

    // 2. Components
    if (dicon.components.length > 0) {
      lines.push(`  // 2. Components`);
      for (const comp of dicon.components) {
        this.generateComponentBinding(lines, comp);
      }
    }

    lines.push(`}`);
    lines.push(``);

    return lines.join("\n");
  }

  private generateComponentBinding(lines: string[], comp: DiconComponentDefinition): void {
    const bindingKey = comp.name || (comp.className ? comp.className.split(".").pop()! : "unknownComponent");
    const simpleClassName = comp.className ? comp.className.split(".").pop()! : undefined;

    // Scope
    let scopeMethod = "inSingletonScope()";
    if (comp.instanceScope === "prototype") {
      scopeMethod = "inTransientScope()";
    } else if (comp.instanceScope === "request") {
      scopeMethod = "inRequestScope()";
    }

    const hasComplexInit = (comp.args && comp.args.length > 0) ||
      (comp.properties && comp.properties.length > 0) ||
      (comp.initMethods && comp.initMethods.length > 0);

    const hasAspects = comp.aspectDefs && comp.aspectDefs.length > 0;
    const hasDestroyMethods = comp.destroyMethods && comp.destroyMethods.length > 0;

    let bindingCode = `  container.bind("${bindingKey}")`;

    if (hasComplexInit) {
      // Dynamic value construction
      bindingCode += `.toDynamicValue((context) => {\n`;
      if (simpleClassName) {
        const ctorArgs = (comp.args || []).map(formatLiteralOrRef).join(", ");
        bindingCode += `    const instance = new ${simpleClassName}(${ctorArgs});\n`;
      } else {
        bindingCode += `    const instance = {} as any;\n`;
      }

      // Properties
      for (const prop of comp.properties || []) {
        const val = formatLiteralOrRef(prop);
        bindingCode += `    instance.${prop.name} = ${val};\n`;
      }

      // Init methods
      for (const initMethod of comp.initMethods || []) {
        const argsStr = (initMethod.args || []).map(formatLiteralOrRef).join(", ");
        bindingCode += `    instance.${initMethod.methodName}(${argsStr});\n`;
      }

      bindingCode += `    return instance;\n`;
      bindingCode += `  }).${scopeMethod}`;
    } else if (simpleClassName) {
      bindingCode += `.to(${simpleClassName}).${scopeMethod}`;
    } else {
      bindingCode += `.toConstantValue({}).${scopeMethod}`;
    }

    // Aspects (via onActivation)
    if (hasAspects) {
      bindingCode += `\n    .onActivation((context, instance: any) => {\n`;
      bindingCode += `      const advisors: PointcutAdvisor[] = [\n`;
      for (const asp of comp.aspectDefs) {
        const pt = asp.pointcut ? `/${asp.pointcut}/` : `/.*+/`;
        bindingCode += `        {\n`;
        bindingCode += `          pointcut: { methodPattern: ${pt} },\n`;
        bindingCode += `          interceptor: context.container.get("${asp.interceptorName}")\n`;
        bindingCode += `        },\n`;
      }
      bindingCode += `      ];\n`;
      bindingCode += `      return applyPointcutAdvisors(instance, "${simpleClassName || bindingKey}", advisors);\n`;
      bindingCode += `    })`;
    }

    // Destroy methods (via onDeactivation)
    if (hasDestroyMethods) {
      for (const dm of comp.destroyMethods) {
        bindingCode += `\n    .onDeactivation((instance: any) => {\n`;
        bindingCode += `      if (typeof instance.${dm.methodName} === "function") {\n`;
        bindingCode += `        instance.${dm.methodName}();\n`;
        bindingCode += `      }\n`;
        bindingCode += `    })`;
      }
    }

    bindingCode += `;`;
    lines.push(bindingCode);
    lines.push(``);
  }
}
