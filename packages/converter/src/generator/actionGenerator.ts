import { SeasarClassIR, SeasarMethodIR, SeasarFieldIR } from "../ir/seasarIR";
import { mapJavaTypeToTs, isBuiltinType } from "./tsGenerator";

function formatTsDoc(doc?: string, indent: string = ""): string[] {
  if (!doc) return [];
  const lines = doc.split("\n").map(l => l.trim());
  const res: string[] = [`${indent}/**`];
  for (const line of lines) {
    res.push(`${indent} * ${line}`);
  }
  res.push(`${indent} */`);
  return res;
}

/**
 * Seasar2 SA-Struts の Action クラスを TypeScript に変換するコードジェネレータ
 */
export class ActionTsGenerator {
  /**
   * Action クラスの TypeScript ソースコードを生成する
   */
  generateActionCode(ir: SeasarClassIR): string {
    const lines: string[] = [];

    // Core & Inversify imports
    lines.push(`import { injectable, inject } from "inversify";`);
    lines.push(`import { ActionResult, view, redirect, json } from "@seasar2ts/core";`);

    // 参照している型・インジェクション対象を収集
    const referencedServices = new Set<string>();
    const referencedForms = new Set<string>();
    const referencedEntities = new Set<string>();

    for (const f of ir.fields) {
      const ft = mapJavaTypeToTs(f.type).replace(/\[\]$/, "");
      if (!isBuiltinType(ft)) {
        if (ft.endsWith("Service") || ft.endsWith("Logic")) {
          referencedServices.add(ft);
        } else if (ft.endsWith("Form") || ft.endsWith("Dto")) {
          referencedForms.add(ft);
        } else if (ft.endsWith("Dao")) {
          referencedServices.add(ft);
        } else {
          referencedEntities.add(ft);
        }
      }
    }

    for (const m of ir.methods) {
      for (const p of m.parameters) {
        const pt = mapJavaTypeToTs(p.type).replace(/\[\]$/, "");
        if (!isBuiltinType(pt)) {
          if (pt.endsWith("Form") || pt.endsWith("Dto")) {
            referencedForms.add(pt);
          } else {
            referencedEntities.add(pt);
          }
        }
      }
    }

    for (const s of referencedServices) {
      if (s.endsWith("Dao")) {
        lines.push(`import { ${s} } from "../dao/${s}";`);
      } else {
        lines.push(`import { ${s} } from "../logic/${s}";`);
      }
    }

    for (const f of referencedForms) {
      lines.push(`import { ${f} } from "./${f}";`);
    }

    for (const e of referencedEntities) {
      lines.push(`import { ${e} } from "../entity/${e}";`);
    }

    lines.push(``);

    // Class TSDoc
    if (ir.docComment) {
      lines.push(...formatTsDoc(ir.docComment));
    } else {
      lines.push(`// Generated by Seasar2ts for Action: ${ir.className}`);
    }

    lines.push(`@injectable()`);
    lines.push(`export class ${ir.className} {`);

    // フィールドをバインディング対象（Logic/Service）と通常フィールド（Form等）に分類
    const bindingFields = ir.fields.filter(f => f.isBinding || f.type.endsWith("Service") || f.type.endsWith("Logic") || f.type.endsWith("Dao"));
    const formFields = ir.fields.filter(f => !bindingFields.includes(f));

    // コンストラクタ生成
    if (bindingFields.length > 0) {
      lines.push(`  constructor(`);
      const ctorParams = bindingFields.map(f => {
        const tsType = mapJavaTypeToTs(f.type);
        return `    @inject("${f.type}") private ${f.name}: ${tsType}`;
      });
      lines.push(ctorParams.join(",\n"));
      lines.push(`  ) {}`);
      lines.push(``);
    } else {
      lines.push(`  constructor() {}`);
      lines.push(``);
    }

    // Form/パブリックフィールドの宣言
    for (const field of formFields) {
      const tsType = mapJavaTypeToTs(field.type);
      if (field.docComment) {
        lines.push(...formatTsDoc(field.docComment, "  "));
      }
      lines.push(`  ${field.visibility} ${field.name} = new ${tsType}();`);
    }
    if (formFields.length > 0) {
      lines.push(``);
    }

    // メソッドの生成
    const baseActionName = ir.className.replace(/(?:Action|Controller)$/, "").replace(/^[A-Z]/, c => c.toLowerCase());

    for (const method of ir.methods) {
      if (method.docComment) {
        lines.push(...formatTsDoc(method.docComment, "  "));
      }

      const paramsDecl = method.parameters
        .map(p => `${p.name}?: ${mapJavaTypeToTs(p.type)}`)
        .join(", ");

      lines.push(`  async ${method.name}(${paramsDecl}): Promise<ActionResult> {`);

      const lowerName = method.name.toLowerCase();
      if (lowerName === "index") {
        lines.push(`    return view("${baseActionName}List.jsp");`);
      } else if (/^(?:submit|save|insert|update|delete|create)/.test(lowerName)) {
        lines.push(`    return redirect("/${baseActionName}/index");`);
      } else if (/^(?:show|detail|view)/.test(lowerName)) {
        lines.push(`    return view("${baseActionName}Detail.jsp");`);
      } else {
        lines.push(`    return view("${baseActionName}.jsp");`);
      }

      lines.push(`  }`);
      lines.push(``);
    }

    lines.push(`}`);
    return lines.join("\n");
  }

  /**
   * ActionForm / DTO クラスの TypeScript ソースコードを生成する
   */
  generateFormCode(ir: SeasarClassIR): string {
    const lines: string[] = [];

    if (ir.docComment) {
      lines.push(...formatTsDoc(ir.docComment));
    } else {
      lines.push(`// Generated by Seasar2ts for Form/DTO: ${ir.className}`);
    }

    lines.push(`export class ${ir.className} {`);

    for (const field of ir.fields) {
      const tsType = mapJavaTypeToTs(field.type);
      if (field.docComment) {
        lines.push(...formatTsDoc(field.docComment, "  "));
      }
      lines.push(`  ${field.name}!: ${tsType};`);
    }

    lines.push(`}`);
    return lines.join("\n");
  }
}
