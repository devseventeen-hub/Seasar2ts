import { SeasarClassIR, SeasarFieldIR, SeasarMethodIR } from "../ir/seasarIR";
import { DiconDataSourceConfig } from "@seasar2ts/core";

/**
 * Java の型名を TypeScript の型名に変換する
 */
export function mapJavaTypeToTs(javaType: string): string {
  const trimmed = javaType.trim();

  // 配列・List
  const listMatch = trimmed.match(/^(?:List|Collection|Set)<(.+)>$/);
  if (listMatch) {
    return `${mapJavaTypeToTs(listMatch[1])}[]`;
  }
  if (trimmed.endsWith("[]")) {
    return `${mapJavaTypeToTs(trimmed.slice(0, -2))}[]`;
  }

  // プリミティブ & 基本型
  switch (trimmed) {
    case "int":
    case "Integer":
    case "long":
    case "Long":
    case "short":
    case "double":
    case "Double":
    case "float":
    case "Float":
    case "BigDecimal":
      return "number";
    case "String":
    case "char":
    case "Character":
      return "string";
    case "boolean":
    case "Boolean":
      return "boolean";
    case "Date":
    case "Timestamp":
      return "Date";
    case "void":
    case "Void":
      return "void";
    case "Object":
      return "any";
    default:
      return trimmed;
  }
}

export function isBuiltinType(typeName: string): boolean {
  return [
    "number",
    "string",
    "boolean",
    "void",
    "any",
    "Date",
    "unknown",
    "never",
    "undefined",
    "null"
  ].includes(typeName);
}

/**
 * SeasarClassIR から TypeScript コードを生成するジェネレータ
 */
export class SeasarTsGenerator {
  /**
   * クラスIRの種類に応じて適切な TS コードを生成する
   */
  generateClassCode(ir: SeasarClassIR): string {
    switch (ir.layer) {
      case "entity":
        return this.generateEntityCode(ir);
      case "dao":
        return this.generateDaoCode(ir);
      case "logic":
      case "action":
      default:
        return this.generateServiceCode(ir);
    }
  }

  /**
   * Entity / POJO Bean の TypeScript コード生成
   */
  generateEntityCode(ir: SeasarClassIR): string {
    const lines: string[] = [];
    lines.push(`// Generated by Seasar2ts from ${ir.className}.java`);
    lines.push(`export class ${ir.className} {`);

    for (const field of ir.fields) {
      const tsType = mapJavaTypeToTs(field.type);
      lines.push(`  ${field.name}!: ${tsType};`);
    }

    lines.push(`}`);
    return lines.join("\n");
  }

  /**
   * S2Dao (Interface / Class) の TypeScript 具象クラスコード生成
   * SQL-first と 自動クエリ生成 (AutoSqlGenerator) のハイブリッドコードを出力
   */
  generateDaoCode(ir: SeasarClassIR): string {
    const lines: string[] = [];
    lines.push(`import { injectable, inject } from "inversify";`);
    lines.push(`import { Database, executeAutoOrFileQuery } from "@seasar2ts/core";`);

    // 参照しているカスタム型（Entity等）を収集してインポート
    const referencedTypes = new Set<string>();
    for (const m of ir.methods) {
      const ret = mapJavaTypeToTs(m.returnType).replace(/\[\]$/, "");
      if (!isBuiltinType(ret)) referencedTypes.add(ret);
      for (const p of m.parameters) {
        const pt = mapJavaTypeToTs(p.type).replace(/\[\]$/, "");
        if (!isBuiltinType(pt)) referencedTypes.add(pt);
      }
    }
    for (const t of referencedTypes) {
      lines.push(`import { ${t} } from "../entity/${t}";`);
    }

    lines.push(``);
    lines.push(`// Generated by Seasar2ts for S2Dao: ${ir.className}`);
    lines.push(`@injectable()`);
    lines.push(`export class ${ir.className} {`);
    lines.push(`  constructor(`);
    lines.push(`    @inject("Database") private db: Database`);
    lines.push(`  ) {}`);
    lines.push(``);

    for (const method of ir.methods) {
      const tsReturnType = mapJavaTypeToTs(method.returnType);
      const isList = tsReturnType.endsWith("[]");
      const baseType = isList ? tsReturnType.slice(0, -2) : tsReturnType;

      const paramsDecl = method.parameters
        .map(p => `${p.name}: ${mapJavaTypeToTs(p.type)}`)
        .join(", ");

      const sqlPath = method.sqlFile
        ? `"${method.sqlFile}"`
        : `"${ir.className.toLowerCase().replace(/dao$/, "")}/${method.name}.sql"`;

      const entityArg = baseType !== "any" && baseType !== "string" && baseType !== "number" && baseType !== "void"
        ? baseType
        : "undefined";

      const paramArgsList = method.parameters.map(p => p.name).join(", ");

      lines.push(`  async ${method.name}(${paramsDecl}): Promise<${tsReturnType}> {`);
      lines.push(`    return await executeAutoOrFileQuery({`);
      lines.push(`      db: this.db,`);
      lines.push(`      daoName: "${ir.className}",`);
      lines.push(`      methodName: "${method.name}",`);
      lines.push(`      sqlRelativePath: ${sqlPath},`);
      lines.push(`      args: [${paramArgsList}],`);
      lines.push(`      entityClass: ${entityArg} as any`);
      lines.push(`    });`);
      lines.push(`  }`);
      lines.push(``);
    }

    lines.push(`}`);
    return lines.join("\n");
  }

  /**
   * Action / Logic クラスの TypeScript コード生成 (Constructor Injection 化)
   */
  generateServiceCode(ir: SeasarClassIR): string {
    const lines: string[] = [];
    lines.push(`import { injectable, inject } from "inversify";`);

    // 参照している型・インジェクション対象を収集
    const referencedTypes = new Set<string>();
    for (const f of ir.fields) {
      const ft = mapJavaTypeToTs(f.type).replace(/\[\]$/, "");
      if (!isBuiltinType(ft)) referencedTypes.add(ft);
    }
    for (const m of ir.methods) {
      const ret = mapJavaTypeToTs(m.returnType).replace(/\[\]$/, "");
      if (!isBuiltinType(ret)) referencedTypes.add(ret);
      for (const p of m.parameters) {
        const pt = mapJavaTypeToTs(p.type).replace(/\[\]$/, "");
        if (!isBuiltinType(pt)) referencedTypes.add(pt);
      }
    }

    for (const t of referencedTypes) {
      if (t.endsWith("Dao")) {
        lines.push(`import { ${t} } from "../dao/${t}";`);
      } else if (t.endsWith("Service") || t.endsWith("Logic")) {
        lines.push(`import { ${t} } from "../logic/${t}";`);
      } else {
        lines.push(`import { ${t} } from "../entity/${t}";`);
      }
    }

    lines.push(``);
    lines.push(`// Generated by Seasar2ts for: ${ir.className}`);
    lines.push(`@injectable()`);
    lines.push(`export class ${ir.className} {`);

    // Binding 対象のフィールドをコンストラクタ引数に変換
    const bindingFields = ir.fields.filter(f => f.isBinding);
    const normalFields = ir.fields.filter(f => !f.isBinding);

    if (bindingFields.length > 0) {
      lines.push(`  constructor(`);
      const ctorParams = bindingFields.map(f => {
        const tsType = mapJavaTypeToTs(f.type);
        return `    @inject("${f.type}") private ${f.name}: ${tsType}`;
      });
      lines.push(ctorParams.join(",\n"));
      lines.push(`  ) {}`);
      lines.push(``);
    } else {
      lines.push(`  constructor() {}`);
      lines.push(``);
    }

    for (const field of normalFields) {
      const tsType = mapJavaTypeToTs(field.type);
      lines.push(`  ${field.visibility} ${field.name}!: ${tsType};`);
    }

    for (const method of ir.methods) {
      const tsReturnType = mapJavaTypeToTs(method.returnType);
      const paramsDecl = method.parameters
        .map(p => `${p.name}: ${mapJavaTypeToTs(p.type)}`)
        .join(", ");

      const isAsync = method.isTransactional ? "async " : "";
      const returnPromise = method.isTransactional && !tsReturnType.startsWith("Promise<")
        ? `Promise<${tsReturnType}>`
        : tsReturnType;

      lines.push(`  ${isAsync}${method.name}(${paramsDecl}): ${returnPromise} {`);
      lines.push(`    // TODO: implement business logic ported from Java`);
      if (tsReturnType === "number") lines.push(`    return 0;`);
      else if (tsReturnType === "string") lines.push(`    return "";`);
      else if (tsReturnType === "boolean") lines.push(`    return false;`);
      else if (tsReturnType !== "void") lines.push(`    return null as any;`);
      lines.push(`  }`);
      lines.push(``);
    }

    lines.push(`}`);
    return lines.join("\n");
  }

  /**
   * アプリケーション全体のコンテナ初期化スクリプト (container.ts) を生成する
   * S2HierarchicalContainer (階層コンテナ) および プラガブル DB Driver をサポート
   */
  generateContainerBootstrap(options?: { dbConfig?: DiconDataSourceConfig }): string {
    const dbConfig = options?.dbConfig;
    let driverImport = "MockDatabase";
    let dbInitCode = "  const db = dbInstance || new MockDatabase();";

    if (dbConfig?.dbType === "postgresql") {
      driverImport = "PostgresDriver";
      const host = dbConfig.host || "localhost";
      const port = dbConfig.port || 5432;
      const database = dbConfig.database || "app";
      const user = dbConfig.user || "postgres";
      const password = dbConfig.password || "";

      dbInitCode = `  const db = dbInstance || new PostgresDriver({
    host: process.env.DB_HOST || "${host}",
    port: parseInt(process.env.DB_PORT || "${port}", 10),
    database: process.env.DB_NAME || "${database}",
    user: process.env.DB_USER || "${user}",
    password: process.env.DB_PASSWORD || "${password}"
  });`;
    } else if (dbConfig?.dbType === "sqlite") {
      driverImport = "SQLiteDriver";
      const filename = dbConfig.database || "data.db";
      dbInitCode = `  const db = dbInstance || new SQLiteDriver({
    filename: process.env.DB_FILE || "${filename}"
  });`;
    }

    return `import "reflect-metadata";
import * as path from "path";
import {
  S2HierarchicalContainer,
  autoBind,
  applyInterceptors,
  applyPointcutAdvisors,
  PointcutAdvisor,
  TxInterceptor,
  LogInterceptor,
  ${driverImport},
  Database
} from "@seasar2ts/core";

export function initContainer(dbInstance?: Database): S2HierarchicalContainer {
  // 1. Root コンテナの生成 (共通リソース・DAO層)
  const rootContainer = new S2HierarchicalContainer("root");

${dbInitCode}
  rootContainer.bind<Database>("Database").toConstantValue(db);

  // 2. 共通 Interceptor の登録
  const txInterceptor = new TxInterceptor(db);
  const logInterceptor = new LogInterceptor();
  rootContainer.bind("TxInterceptor").toConstantValue(txInterceptor);
  rootContainer.bind("LogInterceptor").toConstantValue(logInterceptor);

  const baseDir = __dirname;

  // Root コンテナに DAO を自動登録
  rootContainer.autoBind({ baseDir: path.join(baseDir, "dao") });

  // 3. Web 用子コンテナの生成 (Action / Logic 層)
  const webContainer = rootContainer.createChild("web");
  webContainer.autoBind({ baseDir: path.join(baseDir, "logic") });
  webContainer.autoBind({ baseDir: path.join(baseDir, "action") });

  return rootContainer;
}
`;
  }
}
